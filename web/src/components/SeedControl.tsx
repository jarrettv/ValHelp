const SOURCE: Record<WorldSource, { icon: () => ReactElement; label: string; title: string }> = {
  public: { icon: GlobeIcon, label: '', title: 'A public world' },
  server: { icon: ServerIcon, label: 'server', title: 'Generated by the server' },
  local: { icon: DeviceIcon, label: 'this device', title: 'Generated in this browser and kept on this device' },
  pinned: { icon: CloudIcon, label: 'pinned', title: 'Pinned to your account: kept on this device and generated on your others' },
};

/** Valheim seeds are at most 10 characters. */
const SEED_MAX = 10;

interface SeedControlProps {
  seed: string;
  /// Where the shown world comes from (badge on the pill).
  source: WorldSource;
  /// The site owner: can open any seed on the server and manage the public worlds.
  isOwner: boolean;
  onOpen: (seed: string, how: OpenSeed) => void;
  /// A world was removed from this device.
  onRemoved?: (seed: string) => void;
  className?: string;
}

export default function SeedControl({ seed, source, isOwner, onOpen, onRemoved, className }: SeedControlProps) {
  const [open, setOpen] = useState(false);
  const [other, setOther] = useState('');
  const [confirmRemove, setConfirmRemove] = useState<string | null>(null);
  const root = useRef<HTMLDivElement>(null);
  const qc = useQueryClient();
  const { status: auth } = useAuth();
  const loggedIn = !!auth?.id;
  const { seeds: publicSeeds } = usePublicWorlds();
  const pub = publicSeeds ?? [];
  const pins = usePinnedWorlds(loggedIn);
  const locals = useLocalWorlds(open) ?? [];
  const localSeeds = new Set(locals.map(w => w.seed));
  const deviceWorlds = locals.filter(w => !pins.pins.includes(w.seed));
  const full = deviceWorlds.length >= LOCAL_WORLD_LIMIT;

  const { data: mySeeds } = useQuery<WorldListItem[]>({
    queryKey: ['worlds-list'],
    queryFn: () => fetch('/api/worlds/list', { credentials: 'include' }).then(r => (r.ok ? r.json() : [])),
    enabled: isOwner && open,
    staleTime: 30_000,
  });

  const save = useMutation({
    mutationFn: async (seeds: string[]) => {
      const r = await fetch('/api/admin/worlds/public', {
        method: 'PUT', credentials: 'include', headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ seeds }),
      });
      if (!r.ok) throw new Error(await r.text() || `HTTP ${r.status}`);
      return (await r.json()).seeds as string[];
    },
    onSuccess: seeds => qc.setQueryData(['public-worlds'], seeds),
  });

  // Close on a click elsewhere or Escape.
  useEffect(() => {
    if (!open) return;
    const onDown = (e: PointerEvent) => { if (!root.current?.contains(e.target as Node)) setOpen(false); };
    const onKey = (e: KeyboardEvent) => { if (e.key === 'Escape') setOpen(false); };
    document.addEventListener('pointerdown', onDown);
    document.addEventListener('keydown', onKey);
    return () => { document.removeEventListener('pointerdown', onDown); document.removeEventListener('keydown', onKey); };
  }, [open]);
  useEffect(() => { if (!open) setConfirmRemove(null); }, [open]);

  const go = (s: string, how: OpenSeed = {}) => {
    setOpen(false);
    setOther('');
    onOpen(s, how);
  };
  const pinPublic = (s: string) => save.mutate([...pub, s]);
  const unpinPublic = (s: string) => save.mutate(pub.filter(x => x !== s));
  const makeDefault = (s: string) => save.mutate([s, ...pub.filter(x => x !== s)]);
  async function remove(s: string) {
    if (confirmRemove !== s) { setConfirmRemove(s); return; }
    setConfirmRemove(null);
    await deleteLocalWorld(s);
    track('local_delete', s);
    onRemoved?.(s);
  }

  // The generate box: a public world just opens; anything else is generated here
  // (or opened, if this device or the account already has it).
  const typed = other.trim();
  const known = pub.includes(typed) || localSeeds.has(typed) || pins.pins.includes(typed);
  const blocked = !!typed && !known && full;
  function submit() {
    if (!typed || blocked) return;
    if (pub.includes(typed)) go(typed);
    else go(typed, { local: isOwner, generate: true });
  }

  const others = (mySeeds ?? []).filter(w => !pub.includes(w.seed));
  if (isOwner && source === 'server' && !others.some(w => w.seed === seed))
    others.unshift({ seed, lastViewAt: new Date().toISOString() });

  const Src = SOURCE[source];
  return (
    <div className={`seed-control ${className ?? ''}`} ref={root}>
      <button className={`seed-control-pill src-${source}`} onClick={() => setOpen(o => !o)} aria-expanded={open}
              aria-haspopup="listbox" title={`Change world · ${Src.title}`}>
        <Src.icon />
        <span className="seed-control-name">{seed}</span>
        {Src.label && <span className={`seed-control-src src-${source}`}>{Src.label}</span>}
        <Chevron open={open} />
      </button>
      {open && (
        <div className="seed-control-menu">
          <div className="seed-control-scroll">
            <div className="seed-control-label"><GlobeIcon /> Public worlds</div>
            <ul role="listbox" aria-label="Public worlds">
              {pub.map((s, i) => (
                <li key={s} className="seed-control-row">
                  <button role="option" aria-selected={s === seed} className={`seed-control-pick${s === seed ? ' current' : ''}`}
                          onClick={() => go(s)}>
                    <span className="seed-control-name">{s}</span>
                    {i === 0 && <span className="seed-control-badge">default</span>}
                  </button>
                  {isOwner && (
                    <span className="seed-control-actions">
                      {i > 0 && (
                        <button className="seed-control-icon" title="Make this the default world" onClick={() => makeDefault(s)}
                                disabled={save.isPending}><StarIcon on={false} /></button>
                      )}
                      {pub.length > 1 && (
                        <button className="seed-control-icon on" title="Unpin: hide from the public" onClick={() => unpinPublic(s)}
                                disabled={save.isPending}><PinIcon on /></button>
                      )}
                    </span>
                  )}
                </li>
              ))}
            </ul>

            {loggedIn && pins.pins.length > 0 && (
              <>
                <div className="seed-control-label src-pinned"><CloudIcon /> Pinned to your account
                  <span className="seed-control-count">{pins.pins.length}/{pins.limit}</span></div>
                <ul role="listbox" aria-label="Pinned worlds">
                  {pins.pins.map(s => (
                    <li key={s} className="seed-control-row">
                      <button role="option" aria-selected={s === seed && source === 'pinned'}
                              className={`seed-control-pick${s === seed && source === 'pinned' ? ' current' : ''}`}
                              onClick={() => go(s, { local: true })}>
                        <span className="seed-control-name">{s}</span>
                        <span className="seed-control-when" title={localSeeds.has(s) ? 'Kept on this device' : 'Generated when you open it'}>
                          {localSeeds.has(s) ? 'on device' : 'not here yet'}
                        </span>
                      </button>
                      <span className="seed-control-actions">
                        <button className="seed-control-icon on" title="Unpin: keep it on this device only"
                                onClick={() => pins.setPinned(s, false)} disabled={pins.busy}><PinIcon on /></button>
                      </span>
                    </li>
                  ))}
                </ul>
              </>
            )}

            <div className="seed-control-label src-local"><DeviceIcon /> On this device
              <span className="seed-control-count" title={`This device keeps up to ${LOCAL_WORLD_LIMIT} worlds`}>
                {deviceWorlds.length}/{LOCAL_WORLD_LIMIT}</span></div>
            {deviceWorlds.length === 0
              ? <div className="seed-control-hint">Worlds you generate are kept here.</div>
              : (
                <ul role="listbox" aria-label="Worlds on this device">
                  {deviceWorlds.map(w => (
                    <li key={w.seed} className="seed-control-row">
                      <button role="option" aria-selected={w.seed === seed && source === 'local'}
                              className={`seed-control-pick${w.seed === seed && source === 'local' ? ' current' : ''}`}
                              onClick={() => go(w.seed, { local: true })}>
                        <span className="seed-control-name">{w.seed}</span>
                        <span className="seed-control-when" title="Last opened">{formatAgo(w.openedAt)}</span>
                      </button>
                      <span className="seed-control-actions">
                        {loggedIn && (
                          <button className="seed-control-icon"
                                  title={pins.pins.length >= pins.limit ? `You can pin up to ${pins.limit} worlds` : 'Pin to your account: open it in any browser'}
                                  onClick={() => pins.setPinned(w.seed, true)} disabled={pins.busy || pins.pins.length >= pins.limit}>
                            <PinIcon on={false} /></button>
                        )}
                        <button className={`seed-control-icon danger${confirmRemove === w.seed ? ' confirm' : ''}`}
                                title={confirmRemove === w.seed ? 'Click again to remove it from this device' : 'Remove from this device'}
                                onClick={() => remove(w.seed)}><TrashIcon /></button>
                      </span>
                    </li>
                  ))}
                </ul>
              )}
            {!loggedIn && deviceWorlds.length > 0 && (
              <div className="seed-control-hint"><Link to="/auth/login">Log in</Link> to pin worlds and open them in any browser.</div>
            )}

            {isOwner && others.length > 0 && (
              <>
                <div className="seed-control-label"><ServerIcon /> Server seeds</div>
                <ul role="listbox" aria-label="Server seeds">
                  {others.map(w => (
                    <li key={w.seed} className="seed-control-row">
                      <button role="option" aria-selected={w.seed === seed && source === 'server'}
                              className={`seed-control-pick${w.seed === seed && source === 'server' ? ' current' : ''}`} onClick={() => go(w.seed)}>
                        <span className="seed-control-name">{w.seed}</span>
                        <span className="seed-control-when">{formatAgo(new Date(w.lastViewAt).getTime())}</span>
                      </button>
                      <span className="seed-control-actions">
                        <button className="seed-control-icon" title="Pin: make it a public world" onClick={() => pinPublic(w.seed)}
                                disabled={save.isPending}><PinIcon on={false} /></button>
                      </span>
                    </li>
                  ))}
                </ul>
              </>
            )}
          </div>
          {save.isError && <div className="seed-control-error">{(save.error as Error).message}</div>}
          {pins.error && <div className="seed-control-error">{pins.error.message}</div>}

          {/* Any seed, generated in this browser. */}
          <form className="seed-control-other" onSubmit={e => { e.preventDefault(); submit(); }}>
            <input value={other} onChange={e => setOther(e.target.value)} maxLength={SEED_MAX}
                   placeholder="Any seed…" aria-label="Seed" autoCapitalize="off" autoCorrect="off" spellCheck={false} />
            <button type="submit" disabled={!typed || blocked}
                    title={pub.includes(typed) ? 'Open this public world' : 'Generate this seed in your browser'}>
              {known ? 'Open' : 'Generate'}
            </button>
            {isOwner && (
              <button type="button" className="secondary" disabled={!typed} onClick={() => go(typed)}
                      title="Open on the server (seedgen)"><ServerIcon /></button>
            )}
          </form>
          <div className={`seed-control-foot${blocked ? ' warn' : ''}`}>
            {blocked
              ? `This device holds ${LOCAL_WORLD_LIMIT} worlds. Remove one to make room.`
              : 'Runs in your browser and takes about a minute.'}
          </div>
        </div>
      )}
    </div>
  );
}

function formatAgo(at: number): string {
  const min = Math.max(1, Math.round((Date.now() - at) / 60000));
  if (min < 60) return `${min}m`;
  const hr = Math.round(min / 60);
  if (hr < 48) return `${hr}h`;
  return `${Math.round(hr / 24)}d`;
}
