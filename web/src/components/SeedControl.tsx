import { useEffect, useRef, useState, type ReactElement } from 'react';
import { Link } from 'react-router';
import { useMutation, useQuery, useQueryClient } from '@tanstack/react-query';
import { useAuth } from '../contexts/AuthContext';
import { usePublicWorlds } from './publicWorlds';
import { usePinnedWorlds } from './pinnedWorlds';
import { LOCAL_WORLD_LIMIT, deleteLocalWorld, useLocalWorlds } from '../worldgen/localWorlds';
import { track } from '../lib/analytics';
import type { WorldSource } from '../Worlds';
import './SeedControl.css';

// Seed picker over the world map, in sections:
//   Public worlds    — anyone; the site owner can pin/unpin them and choose the default.
//   Pinned           — a logged-in user's worlds that follow them to other browsers
//                      (only the seed is kept; each browser generates it once).
//   On this device   — worlds generated in this browser (up to LOCAL_WORLD_LIMIT).
//   Server seeds     — the owner's seeds generated by seedgen.
// and a box to generate any seed in the browser. The API enforces who may open
// what on the server (api/ModuleWorlds/WorldsPublic.cs).

interface WorldListItem { seed: string; lastViewAt: string }

/** How to open a seed: in this browser (`local`), generating it straight away (`generate`). */
export interface OpenSeed { local?: boolean; generate?: boolean }

